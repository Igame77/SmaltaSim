from dataclasses import dataclass
from typing import List, Dict, Optional, Any
import time

@dataclass
class Question:
    id: str
    category: str       # e.g. "ВСП.01", "ВСП.02", "ВСП.03"
    topic: str          # e.g. "Станция СПС-5М «Фасоль»"
    text: str
    options: List[str]  # 4 choices
    correct_idx: int    # 0..3
    explanation: str

@dataclass
class QuizResult:
    test_id: str
    test_title: str
    category: str
    total_questions: int
    correct_answers: int
    score_percent: float
    grade: int           # 2, 3, 4, 5
    grade_text: str      # "Отлично", "Хорошо", etc.
    time_spent_seconds: int
    answers_detail: List[Dict[str, Any]]


