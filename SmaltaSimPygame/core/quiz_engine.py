class QuizSession:
    def __init__(self, test_id: str, student_info: Optional[Dict[str, Any]] = None):
        tests = QuizBank.get_all_tests()
        if test_id not in tests:
            test_id = "vsp_comprehensive"

        self.test_def = tests[test_id]
        self.test_id = test_id
        self.test_title = self.test_def["title"]
        self.category = self.test_def["category"]
        self.questions: List[Question] = self.test_def["questions"]
        self.student_info = student_info or {"name": "Курсант", "group": "ВУЦ-РЭБ", "variant": 1}

        self.current_idx: int = 0
        self.user_answers: Dict[int, int] = {}  # q_idx -> chosen_option_idx
        self.start_time: float = time.time()
        self.finish_time: Optional[float] = None
        self.is_finished: bool = False

    @property
    def total_questions(self) -> int:
        return len(self.questions)

    @property
    def current_question(self) -> Optional[Question]:
        if 0 <= self.current_idx < len(self.questions):
            return self.questions[self.current_idx]
        return None

    def select_answer(self, option_idx: int):
        self.user_answers[self.current_idx] = option_idx

    def get_selected_answer(self) -> Optional[int]:
        return self.user_answers.get(self.current_idx)

    def next_question(self) -> bool:
        if self.current_idx < len(self.questions) - 1:
            self.current_idx += 1
            return True
        return False

    def prev_question(self) -> bool:
        if self.current_idx > 0:
            self.current_idx -= 1
            return True
        return False

    def finish_quiz(self) -> QuizResult:
        self.is_finished = True
        self.finish_time = time.time()
        time_spent = int(self.finish_time - self.start_time)

        correct_count = 0
        answers_detail = []

        for i, q in enumerate(self.questions):
            chosen = self.user_answers.get(i)
            is_correct = (chosen == q.correct_idx)
            if is_correct:
                correct_count += 1
            answers_detail.append({
                "question_id": q.id,
                "text": q.text,
                "chosen_idx": chosen,
                "correct_idx": q.correct_idx,
                "is_correct": is_correct,
                "explanation": q.explanation
            })

        total = max(1, len(self.questions))
        score_percent = round((correct_count / total) * 100.0, 1)

        # Russian academic grading standard:
        # >= 85%: 5 («Отлично»)
        # >= 70%: 4 («Хорошо»)
        # >= 50%: 3 («Удовлетворительно»)
        # < 50%: 2 («Неудовлетворительно»)
        if score_percent >= 85.0:
            grade = 5
            grade_text = "Отлично"
        elif score_percent >= 70.0:
            grade = 4
            grade_text = "Хорошо"
        elif score_percent >= 50.0:
            grade = 3
            grade_text = "Удовлетворительно"
        else:
            grade = 2
            grade_text = "Неудовлетворительно"

        return QuizResult(
            test_id=self.test_id,
            test_title=self.test_title,
            category=self.category,
            total_questions=total,
            correct_answers=correct_count,
            score_percent=score_percent,
            grade=grade,
            grade_text=grade_text,
            time_spent_seconds=time_spent,
            answers_detail=answers_detail
        )
