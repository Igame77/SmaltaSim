    def resolve_path(self, rel_path: str) -> Path:
        """Возвращает абсолютный путь к файлу симулятора или теста."""
        return (self.root_dir / rel_path).resolve()

    def exists(self, rel_path: str) -> bool:
        """Проверяет существование файла на диске."""
        return self.resolve_path(rel_path).exists()

    def launch_simulator(self, sim_id: str) -> Tuple[bool, str]:
        """
        Запускает указанный симулятор в отдельном процессе или в браузере.
        Возвращает (успех, сообщение).
        """
        sim = self.simulators.get(sim_id)
        if not sim:
            return False, f"Неизвестный идентификатор симулятора: {sim_id}"

        target = self.resolve_path(sim["rel_path"])
        if not target.exists():
            return False, f"Файл симулятора не найден: {target}"

        try:
            if sim["kind"] == "html_interactive":
                webbrowser.open(target.as_uri())
                return True, f"Интерактивный симулятор «{sim['name']}» открыт в веб-обозревателе."
            elif sim["kind"] == "standalone_exe":
                # Запуск исполняемого файла с рабочей директорией в его папке
                subprocess.Popen([str(target)], cwd=str(target.parent))
                return True, f"Симулятор «{sim['name']}» успешно запущен."
            else:
                return False, f"Неподдерживаемый тип симулятора: {sim['kind']}"
        except Exception as e:
            return False, f"Ошибка при запуске симулятора «{sim['name']}»: {e}"

    def launch_test(self, rel_path: str) -> Tuple[bool, str]:
        """
        Запускает выбранный easyQuizzy тест в отдельном процессе.
        Возвращает (успех, сообщение).
        """
        target = self.resolve_path(rel_path)
        if not target.exists():
            return False, f"Файл теста не найден: {target}"

        try:
            subprocess.Popen([str(target)], cwd=str(target.parent))
            return True, f"Тест «{target.name}» запущен."
        except Exception as e:
            return False, f"Ошибка при запуске теста «{target.name}»: {e}"

