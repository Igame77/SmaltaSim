def get_solution_root() -> Path:
    """Определяет корневой каталог решения, где расположены папки ВСП01, ВСП02, ВСП03."""
    # 1. Если упаковано PyInstaller
    if getattr(sys, 'frozen', False):
        exe_path = Path(sys.executable).resolve().parent
        if (exe_path / "ВСП01").exists():
            return exe_path
        if (exe_path.parent / "ВСП01").exists():
            return exe_path.parent
        return exe_path

    # 2. Если запускается из исходников
    curr = Path(__file__).resolve().parent
    # Поднимаемся вверх до папки, содержащей ВСП01
    for p in [curr, curr.parent, curr.parent.parent]:
        if (p / "ВСП01").exists():
            return p
    return curr.parent

